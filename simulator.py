"""
simulator.py  -  Smart Traffic Monitor (SLAM mini-project)
 
Pushes SIMULATED traffic readings for six Hyderabad roads to Firebase
Realtime Database every few seconds.
 
IMPORTANT: every number here is generated by code. It is NOT real traffic data.
 
Run   :  py simulator.py
Stop  :  press Ctrl+C in the same terminal
 
Database layout it creates:
  latest/road_1 ... latest/road_6          -> newest reading per road (overwritten each round)
  history/road_1/t<unix_time> ...          -> saved records over time (used later for the Trends chart)
"""
 
import math
import random
import time
from datetime import datetime
 
import firebase_admin
from firebase_admin import credentials, db
 
# ---------------- settings you can change ----------------
KEY_FILE = "serviceAccountKey.json"          # private key (never share / never upload to GitHub)
DATABASE_URL = "https://smart-traffic-moniter-default-rtdb.asia-southeast1.firebasedatabase.app/"
INTERVAL_SECONDS = 5     # how often new readings are generated
HISTORY_EVERY = 120      # save a history record every N rounds (120 x 5 s = every 10 minutes)
# ---------------------------------------------------------
 
# free_flow = normal speed (km/h) when the road is empty
# base      = vehicles counted per minute at a typical busy level
# busy      = how much busier than average this road tends to be
ROADS = [
    {"id": 1, "name": "MG Road (Gachibowli)",  "free_flow": 55, "base": 150, "busy": 1.00},
    {"id": 2, "name": "Tank Bund Road",        "free_flow": 50, "base": 130, "busy": 0.90},
    {"id": 3, "name": "Hitech City Main Road", "free_flow": 60, "base": 170, "busy": 1.10},
    {"id": 4, "name": "Begumpet Main Road",    "free_flow": 45, "base": 140, "busy": 1.05},
    {"id": 5, "name": "LB Nagar Ring Road",    "free_flow": 52, "base": 160, "busy": 1.00},
    {"id": 6, "name": "Kukatpally (JNTU) Road", "free_flow": 48, "base": 145, "busy": 1.10},
]
 
 
def time_factor(hour, weekday):
    """Returns 0..1 : how busy traffic is at this time (peaks near 9:30 and 18:30)."""
    morning = math.exp(-((hour - 9.5) ** 2) / (2 * 1.5 ** 2))
    evening = math.exp(-((hour - 18.5) ** 2) / (2 * 1.8 ** 2))
    factor = 0.15 + 0.70 * max(morning, evening)
    if weekday >= 5:          # Saturday / Sunday are lighter
        factor *= 0.6
    return factor
 
 
def make_reading(road, now):
    """Makes one simulated reading for one road."""
    hour = now.hour + now.minute / 60
    factor = time_factor(hour, now.weekday()) * road["busy"]
    factor += random.uniform(-0.08, 0.08)            # random noise
    factor = max(0.05, min(0.98, factor))
 
    speed = road["free_flow"] * (1 - 0.70 * factor) + random.uniform(-2, 2)
    speed = max(5, min(road["free_flow"], speed))
 
    count = road["base"] * (0.25 + 0.90 * factor) + random.uniform(-8, 8)
    count = max(5, int(count))
 
    ratio = speed / road["free_flow"]
    if ratio < 0.45:
        status = "high"
    elif ratio < 0.70:
        status = "medium"
    else:
        status = "low"
 
    return {
        "road_id": road["id"],
        "road_name": road["name"],
        "speed": round(speed, 1),
        "vehicle_count": count,
        "simulated_status": status,     # from speed rule; NOT the ML prediction
        "hour": now.hour,
        "day_of_week": now.weekday(),   # 0 = Monday
        "timestamp": now.isoformat(timespec="seconds"),
        "ts": int(now.timestamp()),
        "source": "simulated",
    }
 
 
def main():
    cred = credentials.Certificate(KEY_FILE)
    firebase_admin.initialize_app(cred, {"databaseURL": DATABASE_URL})
    root = db.reference("/")
 
    print("Simulator started. Press Ctrl+C to stop.")
    print(f"New readings every {INTERVAL_SECONDS}s, history saved every "
          f"{HISTORY_EVERY * INTERVAL_SECONDS}s.\n")
 
    round_no = 0
    try:
        while True:
            round_no += 1
            now = datetime.now()
            save_history = (round_no - 1) % HISTORY_EVERY == 0
 
            updates = {}
            lines = []
            for road in ROADS:
                reading = make_reading(road, now)
                updates[f"latest/road_{road['id']}"] = reading
                if save_history:
                    updates[f"history/road_{road['id']}/t{reading['ts']}"] = reading
                lines.append(f"  {road['name']:<25} speed {reading['speed']:>5} km/h  "
                             f"count {reading['vehicle_count']:>3}  {reading['simulated_status']}")
 
            try:
                root.update(updates)     # one network call writes all six roads
                tag = " (+history)" if save_history else ""
                print(f"[{now:%H:%M:%S}] round {round_no}: saved to Firebase{tag}")
                print("\n".join(lines))
            except Exception as error:
                print(f"[{now:%H:%M:%S}] Could not write to Firebase, will retry: {error}")
 
            time.sleep(INTERVAL_SECONDS)
    except KeyboardInterrupt:
        print("\nSimulator stopped.")
 
 
if __name__ == "__main__":
    main()
 