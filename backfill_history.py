"""
backfill_history.py  -  fills Firebase 'history' with the last 24 hours of
SIMULATED readings (one reading per road every 10 minutes), so the Trends
chart has data to show.

Run once:  py backfill_history.py
Safe to run again: timestamps are rounded to 10 minutes, so records are
overwritten, not duplicated.

All values are generated by code. They are NOT real traffic data.
"""

from datetime import datetime, timedelta

import firebase_admin
from firebase_admin import credentials, db

# re-use the same rules as simulator.py (importing does not start the simulator)
from simulator import ROADS, KEY_FILE, DATABASE_URL, make_reading

STEP_MINUTES = 10
HOURS_BACK = 24


def main():
    firebase_admin.initialize_app(
        credentials.Certificate(KEY_FILE), {"databaseURL": DATABASE_URL}
    )
    root = db.reference("/")

    now = datetime.now().replace(second=0, microsecond=0)
    end = now - timedelta(minutes=now.minute % STEP_MINUTES)   # round down to 10 min
    steps = HOURS_BACK * 60 // STEP_MINUTES

    total = 0
    for road in ROADS:
        updates = {}
        for k in range(steps):
            moment = end - timedelta(minutes=k * STEP_MINUTES)
            reading = make_reading(road, moment)
            reading["source"] = "simulated_backfill"
            updates[f"history/road_{road['id']}/t{reading['ts']}"] = reading
        root.update(updates)
        total += len(updates)
        print(f"Saved {len(updates)} records for {road['name']}")

    print(f"\nDone. {total} simulated records written to Firebase 'history'.")


if __name__ == "__main__":
    main()